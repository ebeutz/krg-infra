#!/usr/bin/env bash
# Generate imports.tf for adopting the EXISTING router config into OpenTofu state.
#
# RouterOS import IDs are opaque per-object handles (*1, *2A, ...) that only exist on
# the live box, so they can't be written by hand in advance. This script is DISCOVERY
# (read-only GETs against the REST API — the CLAUDE.md exception): it looks each
# object up by its natural key and prints one `import {}` block per resource address.
# Commit the output as imports.tf in the adoption PR; the next deploy-tofu.sh
# plan/apply then imports through the real encrypted state, like any other change.
#
# Usage (on krg-deploy, with VAULT_TOKEN from the krg-deploy AppRole, or ROS_PASSWORD):
#   terraform/krg-router/discover-imports.sh > terraform/krg-router/imports.tf
#
# Settings singletons (dns, clock, identity, ip services, mac-server, ...) need no
# import — their "create" is a set — so they are not listed here.
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
host="${ROS_HOST:-132.239.17.56}"
user="${ROS_USERNAME:-tofu}"
pass="${ROS_PASSWORD:-$(bao kv get -field=password secret/krg-deploy/krg-router)}"
cacert="${here}/router-server.crt"
[[ -r "$cacert" ]] || { echo "missing ${cacert} (the pinned router cert, README step 3)" >&2; exit 1; }

# Credentials go to curl on stdin (-K -), never on argv.
_get() { # <menu path> <key=value>...
  local path="$1"; shift
  local args=()
  for kv in "$@"; do args+=(--data-urlencode "$kv"); done
  local u="${user}:${pass}"
  u=${u//\\/\\\\}   # \ -> \\ (curl config-file escaping)
  u=${u//\"/\\\"}     # " -> \"
  printf 'user = "%s"\n' "$u" \
    | curl -sS --fail -K - --cacert "$cacert" -G "${args[@]}" "https://${host}/rest${path}"
}

# Print an import block for the single NON-dynamic object matching the filters.
imp() { # <resource address> <menu path> <key=value>...
  local addr="$1" path="$2"; shift 2
  local ids n
  ids="$(_get "$path" "$@" | jq -r '[.[] | select(.dynamic != "true")] | map(.[".id"]) | .[]')"
  n="$(grep -c . <<<"$ids" || true)"
  if [[ "$n" -ne 1 ]]; then
    echo "ERROR: ${addr}: expected exactly 1 match for ${path} $*, found ${n}" >&2
    return 1
  fi
  printf 'import {\n  to = %s\n  id = "%s"\n}\n\n' "$addr" "$ids"
}

echo "# GENERATED by discover-imports.sh against ${host} on $(date -u +%Y-%m-%dT%H:%MZ)."
echo "# One-time adoption of the pre-IaC config. Safe to delete after the import apply."
echo

imp 'routeros_interface_bridge.lan' /interface/bridge name=bridge
for p in ether{2..24} sfp-sfpplus{1..4}; do
  imp "routeros_interface_bridge_port.lan[\"${p}\"]" /interface/bridge/port "interface=${p}"
done
imp 'routeros_interface_list.this["WAN"]' /interface/list name=WAN
imp 'routeros_interface_list.this["LAN"]' /interface/list name=LAN
imp 'routeros_interface_list_member.wan' /interface/list/member list=WAN interface=ether1
imp 'routeros_interface_list_member.lan' /interface/list/member list=LAN interface=bridge

imp 'routeros_ip_address.wan' /ip/address address=132.239.17.56/24
imp 'routeros_ip_address.lan' /ip/address address=192.168.1.1/24
imp 'routeros_ip_route.default' /ip/route dst-address=0.0.0.0/0 gateway=132.239.17.1
imp 'routeros_ip_pool.lan' /ip/pool name=dhcp
imp 'routeros_ip_dhcp_server.lan' /ip/dhcp-server name=dhcp1
imp 'routeros_ip_dhcp_server_network.lan' /ip/dhcp-server/network address=192.168.1.0/24
imp 'routeros_ip_firewall_nat.masquerade' /ip/firewall/nat chain=srcnat action=masquerade

imp 'routeros_interface_bridge_port.legacy_wan[0]' /interface/bridge/port interface=ether1
imp 'routeros_ip_dhcp_client.legacy_wan[0]' /ip/dhcp-client interface=ether1
imp 'routeros_ip_dhcp_server_network.legacy_bogus[0]' /ip/dhcp-server/network address=0.0.0.0/24
